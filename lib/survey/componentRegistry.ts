  function makeId(prefix = "field") {
    if (typeof crypto !== "undefined" && "randomUUID" in crypto) {
      return `${prefix}-${crypto.randomUUID()}`;
    }
  
    return `${prefix}-${Date.now()}-${Math.random().toString(36).slice(2)}`;
  }
  
